"""Write requirements.lock with pinned versions and sha256 hashes from PyPI.

Install with:
    python -m pip install --require-hashes --no-deps -r requirements.lock

A swapped or tampered package fails the hash check and is not installed.
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.specifiers import SpecifierSet
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (ROOT / "requirements.txt", ROOT / "requirements-dev.txt")
OUT = ROOT / "requirements.lock"


def pypi(name: str) -> dict:
    url = f"https://pypi.org/pypi/{name}/json"
    with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310 — PyPI only, maintainer script
        return json.load(resp)


def choose_version(data: dict, spec: SpecifierSet) -> str:
    versions = [Version(v) for v in data["releases"] if not Version(v).is_prerelease and spec.contains(v)]
    if not versions:
        raise SystemExit(f"No release of {data['info']['name']} matches {spec}")
    return str(max(versions))


def wanted(req: Requirement) -> bool:
    if req.marker is None:
        return True
    marker = str(req.marker)
    if "extra" in marker:
        return False
    return Marker(marker).evaluate()


def main() -> int:
    queue: list[Requirement] = []
    for src in SOURCES:
        for line in src.read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if line:
                queue.append(Requirement(line))

    pinned: dict[str, tuple[str, list[str]]] = {}
    seen: set[str] = set()
    while queue:
        req = queue.pop(0)
        key = req.name.lower().replace("_", "-")
        if key in seen:
            continue
        if not wanted(req):
            continue
        seen.add(key)
        data = pypi(req.name)
        version = choose_version(data, req.specifier)
        files = data["releases"][version]
        hashes = sorted({f["digests"]["sha256"] for f in files if f.get("digests", {}).get("sha256")})
        if not hashes:
            raise SystemExit(f"No hashes published for {req.name}=={version}")
        pinned[data["info"]["name"]] = (version, hashes)
        for dep in data["info"].get("requires_dist") or []:
            dep_req = Requirement(dep)
            if wanted(dep_req):
                queue.append(dep_req)

    lines = [
        "# Generated by scripts/lock_requirements.py. Do not edit by hand.",
        "# Every file PyPI published for that version is hashed; pip refuses anything else.",
        "",
    ]
    for name in sorted(pinned, key=str.lower):
        version, hashes = pinned[name]
        parts = [f"{name}=={version} \\\n"]
        for i, digest in enumerate(hashes):
            end = "\n" if i == len(hashes) - 1 else " \\\n"
            parts.append(f"    --hash=sha256:{digest}{end}")
        lines.append("".join(parts))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(pinned)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
